using System;
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.UIElements;

namespace Sharq.Core
{
    /// <summary>
    /// Controls when WatchEffect callbacks are executed relative to Unity UI Toolkit layout.
    /// </summary>
    public enum FlushMode
    {
        /// <summary>Runs immediately on prop change, batched once per frame. Default.</summary>
        PreLayout = 0,

        /// <summary>Defers execution until after UI Toolkit layout pass.
        /// Use when the effect reads worldBound / resolvedStyle.</summary>
        PostLayout = 1,
    }

    /// <summary>
    /// Base class for all Sharq UI components. Extends Unity's VisualElement with
    /// Vue-like reactivity, lifecycle hooks, event system, slots, and bind helpers.
    ///
    /// The Build() method is generated by the Sharq Source Generator from .sharq files.
    /// </summary>
    public abstract partial class SusComponent : VisualElement
    {
        // ─── Reactivity helpers ───────────────────────────────────────────

        /// <summary>Create a reactive property.</summary>
        protected Prop<T> P<T>(T initial = default) => new(initial);

        /// <summary>Create a computed (derived) property.</summary>
        protected Computed<T> C<T>(Func<T> fn) => new(fn);

        /// <summary>
        /// Watch a Prop for changes. Returns an IDisposable handle;
        /// disposing it unsubscribes the watcher.
        /// </summary>
        protected WatchHandle Watch<T>(Prop<T> source, Action<T, T> callback)
        {
            if (source == null) throw new ArgumentNullException(nameof(source));
            if (callback == null) throw new ArgumentNullException(nameof(callback));

            source.Changed += callback;
            var h = new WatchHandle(() => source.Changed -= callback);
            TrackBinding(h);
            return h;
        }

        /// <summary>
        /// Watch a Prop for changes, registering the handle in an EffectScope.
        /// The scope owns the handle — calling scope.Dispose() unsubscribes.
        /// </summary>
        protected WatchHandle Watch<T>(Prop<T> source, Action<T, T> callback, EffectScope scope)
        {
            if (scope == null) throw new ArgumentNullException(nameof(scope));
            var h = Watch(source, callback);
            scope.Register(h);
            return h;
        }

        /// <summary>
        /// Create an EffectScope for grouping subscriptions.
        /// Analogous to Vue's effectScope(). Disposing the scope unsubscribes
        /// all watches registered through Watch(prop, cb, scope).
        /// </summary>
        protected EffectScope CreateScope() => new();

        /// <summary>
        /// Shared reactive primitive. Runs fn inside DependencyTracker.Track,
        /// subscribes to all reactive sources (Prop/Computed) read in fn,
        /// and re-runs fn on any invalidation via batched ScheduleBindUpdate.
        /// This is the single source of truth for all reactivity in sus-core.
        /// </summary>
        private WatchHandle ReactiveEffect(Action fn)
        {
            var subs = new System.Collections.Generic.List<IDisposable>();

            void Run()
            {
                foreach (var s in subs) s.Dispose();
                subs.Clear();

                using (DependencyTracker.Track(src =>
                    subs.Add(src.SubscribeInvalidate(() => ScheduleBindUpdate(Run)))))
                {
                    fn();
                }
            }

            Run();
            return new WatchHandle(() =>
            {
                foreach (var s in subs) s.Dispose();
                subs.Clear();
            });
        }

        /// <summary>
        /// Auto-tracking effect. Runs fn immediately, then auto-reruns when any Prop&lt;T&gt;
        /// or Computed&lt;T&gt; read inside fn changes. Equivalent to Vue's watchEffect().
        ///
        /// Example:
        /// <code>
        /// WatchEffect(() => {
        ///     var hp = Health.Value;
        ///     var max = MaxHealth.Value;
        ///     label.text = $"{hp}/{max}";
        /// });
        /// </code>
        /// </summary>
        protected WatchHandle WatchEffect(Action fn)
        {
            if (fn == null) throw new ArgumentNullException(nameof(fn));
            var h = ReactiveEffect(fn);
            TrackBinding(h);
            return h;
        }

        /// <summary>
        /// Auto-tracking effect with flush mode.
        ///
        /// <list type="bullet">
        /// <item><b>PreLayout</b> (default): runs immediately on prop change,
        ///   batched once per frame. Use for data mutations, text updates.</item>
        /// <item><b>PostLayout</b>: defers execution until after Unity UI Toolkit
        ///   completes its layout pass. Use when fn reads worldBound / resolvedStyle.</item>
        /// </list>
        ///
        /// Analogous to Vue watchPostEffect() / React useLayoutEffect.
        /// <code>
        /// WatchEffect(() => {
        ///     PositionSlider(_slider.worldBound.width);
        /// }, FlushMode.PostLayout);
        /// </code>
        /// </summary>
        protected WatchHandle WatchEffect(Action fn, FlushMode flush)
        {
            if (fn == null) throw new ArgumentNullException(nameof(fn));

            if (flush == FlushMode.PostLayout)
            {
                var h = ReactiveEffectPostLayout(fn);
                TrackBinding(h);
                return h;
            }

            return WatchEffect(fn);
        }

        private WatchHandle ReactiveEffectPostLayout(Action fn)
        {
            var subs = new System.Collections.Generic.List<IDisposable>();

            void Run()
            {
                foreach (var s in subs) s.Dispose();
                subs.Clear();

                using (DependencyTracker.Track(src =>
                    subs.Add(src.SubscribeInvalidate(() => ScheduleBindUpdate(Run)))))
                {
                    // Defer execution to after Unity UI Toolkit layout pass
                    schedule.Execute(fn).ExecuteLater(0);
                }
            }

            Run();
            return new WatchHandle(() =>
            {
                foreach (var s in subs) s.Dispose();
                subs.Clear();
            });
        }

        // ─── Binding lifecycle ────────────────────────────────────────────

        private readonly List<WatchHandle> _bindings = new();

        // ─── Batched bind update scheduling ────────────────────────────────

        private readonly HashSet<Action> _pendingBindActions = new();
        private IVisualElementScheduledItem _bindScheduleItem;

        /// <summary>
        /// Batches a bind-update action to execute once per frame.
        /// De-duplicates: same Action is only queued once.
        /// </summary>
        private void ScheduleBindUpdate(Action apply)
        {
            _pendingBindActions.Add(apply);
            _bindScheduleItem ??= schedule.Execute(ApplyAllBindUpdates);
            _bindScheduleItem.ExecuteLater(0);
        }

        private void ApplyAllBindUpdates()
        {
            if (_pendingBindActions.Count == 0) return;
            // Snapshot and clear to allow re-registration during execution
            var actions = new List<Action>(_pendingBindActions);
            _pendingBindActions.Clear();
            foreach (var action in actions)
                action();
        }

        /// <summary>
        /// Creates a WatchHandle for manual subscription tracking.
        /// Use when you need to TrackBinding() for non-standard callbacks
        /// (e.g. Controller.Errors.Changed) that can't use Bind* methods.
        /// </summary>
        protected static WatchHandle CreateWatchHandle(Action unsubscribe)
        {
            return new WatchHandle(unsubscribe);
        }

        /// Registers a binding's WatchHandle so it can be disposed on detach.
        /// Called by all Bind* methods and Watch/WatchEffect.
        /// </summary>
        protected void TrackBinding(WatchHandle h)
        {
            if (h != null) _bindings.Add(h);
        }

        private void DisposeAllBindings()
        {
            for (int i = _bindings.Count - 1; i >= 0; i--)
                _bindings[i].Dispose();
            _bindings.Clear();
            _eventHandlers?.Clear();
        }

