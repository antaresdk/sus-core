        /// per-root service via SusBreakpointService.For(this).
        /// </summary>
        public SusBreakpointService BreakpointService
        {
            get
            {
                if (_breakpointService == null)
                    _breakpointService = SusBreakpointService.For(this);
                return _breakpointService;
            }
            protected set => _breakpointService = value;
        }
        private SusBreakpointService _breakpointService;

        // ─── Click Audit ───────────────────────────────────────────────────

        /// <summary>
        /// Sets a human-readable description of the component for ClickAuditService.
        /// Call once in Created(). When set, every ClickEvent on this element
        /// is checked by the audit (Editor / Development Build only).
        ///
        /// Example:
        /// <code>
        /// protected override void Created()
        /// {
        ///     SetClickAuditDescription("MainMenu.FightButton");
        ///     // ...
        /// }
        /// </code>
        /// </summary>
        protected void SetClickAuditDescription(string description)
        {
#if UNITY_EDITOR || DEVELOPMENT_BUILD
            _clickAuditDescription = description;
#endif
        }

#if UNITY_EDITOR || DEVELOPMENT_BUILD
        /// <summary>
        /// Logs a warning if the click was blocked by a guard condition.
        /// Call inside a ClickEvent handler on early return.
        ///
        /// Example:
        /// if (Disabled.Value) {
        ///     AuditClickBlocked("Disabled");
        ///     return;
        /// }
        /// </summary>
        protected void AuditClickBlocked(string reason)
        {
            var desc = _clickAuditDescription ?? GetType().Name;
            UnityEngine.Debug.LogWarning($"[CallbackAudit] '{desc}' click blocked: {reason}");
        }

        /// <summary>
        /// Logs if the handler ran but took longer than the threshold ms.
        /// </summary>
        protected double AuditClickStart()
        {
            return UnityEngine.Time.realtimeSinceStartupAsDouble;
        }

        protected void AuditClickEnd(double startTime, string action = "OnClick")
        {
            var elapsed = (UnityEngine.Time.realtimeSinceStartupAsDouble - startTime) * 1000.0;
            if (elapsed > 50.0)
            {
                var desc = _clickAuditDescription ?? GetType().Name;
                UnityEngine.Debug.LogWarning($"[CallbackAudit] '{desc}' {action} took {elapsed:F1}ms");
            }
        }
#endif

        // ─── Overlay convenience methods ──────────────────────────────────

        /// <summary>
        /// Adds an element to the nearest OverlayHost in the visual tree.
        /// Traverses up to root to find or create the overlay container.
        /// Returns null if no root panel is attached.
        /// </summary>
        protected OverlayEntry AddToOverlay(VisualElement element, OverlayCategory category,
            bool dismissOnClickOutside = false, System.Action onDismiss = null)
        {
            if (element == null) return null;
            if (panel == null) return null;

            var root = panel.visualTree;
            var overlay = SusBootstrap.GetOrCreateOverlay(root);
            return overlay.AddToOverlay(element, category, dismissOnClickOutside, onDismiss);
        }

        /// <summary>
        /// Removes an element from the nearest OverlayHost.
        /// </summary>
        protected void RemoveFromOverlay(VisualElement element)
        {
            if (element == null || panel == null) return;
            var root = panel.visualTree;
            if (root.childCount == 0) return;
            var last = root.ElementAt(root.childCount - 1);
            if (last is OverlayHost overlay)
                overlay.RemoveFromOverlay(element);
        }

