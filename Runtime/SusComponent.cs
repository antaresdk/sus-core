        /// <summary>
        /// Reactive list binding for v-for. Handles both IEnumerable&lt;T&gt;
        /// and Prop&lt;List&lt;T&gt;&gt; via reflection-based unwrapping.
        /// </summary>
        protected void BindListFor<T>(VisualElement container, object source,
            Func<T, int, VisualElement> factory, Func<T, object> keySelector = null)
        {
            if (container == null || factory == null) return;
            container.Clear();
            if (source == null) return;

            // Unwrap Prop<List<T>> or Prop<IEnumerable<T>>
            var sourceType = source.GetType();
            if (sourceType.IsGenericType && sourceType.GetGenericTypeDefinition() == typeof(Prop<>))
            {
                var valueProp = sourceType.GetProperty("Value");
                if (valueProp != null)
                    source = valueProp.GetValue(source);
            }

            if (source is IEnumerable<T> items)
            {
                int i = 0;
                foreach (var item in items)
                {
                    var child = factory(item, i);
                    if (child != null) container.Add(child);
                    i++;
                }
            }
        }

        /// <summary>
        /// Non-generic fallback for v-for without inferred item type.
        /// </summary>
        protected void BindListFor(VisualElement container, object source,
            Func<object, int, VisualElement> factory, Func<object, object> keySelector = null)
        {
            if (container == null || factory == null) return;
            container.Clear();
            if (source == null) return;

            // Unwrap Prop<List<T>> via reflection
            var sourceType = source.GetType();
            if (sourceType.IsGenericType && sourceType.GetGenericTypeDefinition() == typeof(Prop<>))
            {
                var valueProp = sourceType.GetProperty("Value");
                if (valueProp != null)
                    source = valueProp.GetValue(source);
            }

            if (source is System.Collections.IEnumerable items)
            {
                int i = 0;
                foreach (var item in items)
                {
                    var child = factory(item, i);
                    if (child != null) container.Add(child);
                    i++;
                }
            }
        }
