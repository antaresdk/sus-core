        /// <summary>
        /// Adds an element to the nearest OverlayHost in the visual tree.
        /// Traverses up to root to find or create the overlay container.
        /// Returns null if no root panel is attached.
        /// </summary>
        protected OverlayEntry AddToOverlay(VisualElement element, OverlayCategory category,
            bool dismissOnClickOutside = false, System.Action onDismiss = null)
        {
            if (element == null) return null;
            if (panel == null) return null;

            var root = panel.visualTree;
            var overlay = SusBootstrap.GetOrCreateOverlay(root);
            return overlay.AddToOverlay(element, category, dismissOnClickOutside, onDismiss);
        }

        /// <summary>
        /// Removes an element from the nearest OverlayHost.
        /// </summary>
        protected void RemoveFromOverlay(VisualElement element)
        {
            if (element == null || panel == null) return;
            var root = panel.visualTree;
            if (root.childCount == 0) return;
            var last = root.ElementAt(root.childCount - 1);
            if (last is OverlayHost overlay)
                overlay.RemoveFromOverlay(element);
        }

